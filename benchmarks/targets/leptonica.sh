#!/bin/sh
# Prepare leptonica for a benchmark build, without autotools.
#
#   ./leptonica.sh /b/leptonica
#
# leptonica's configure generates src/endianness.h. Without it the C PREPROCESSOR FAILS on
# allheaders.h — and that failure is silent all the way to the benchmark row:
#
#   no endianness.h -> _preprocess returns None
#                   -> parse falls back to reading allheaders.h as raw text
#                   -> `typedef unsigned char l_uint8;` in environ.h is never seen
#                   -> `pixReadMem(const l_uint8 *, size_t)` does not look like it
#                      takes bytes
#                   -> the producer decides the entry point has no input and hunts for a
#                      SETTER to feed the handle, landing on boxaPlotSides — a plotting
#                      function
#                   -> S1 and S2 refuse the plan, correctly
#                   -> the run reports "all plans refused by a static gate"
#
# Five steps from a missing generated header to a gate verdict about something else
# entirely. This is the reason build prerequisites belong in the case, not in a comment.
set -eu
SRC="${1:-/b/leptonica}"

# aarch64 and x86-64 are both little-endian; the benchmark runs on aarch64. Stated rather
# than detected, because a wrong guess here changes what the library computes.
cat > "$SRC/src/endianness.h" <<'HDR'
#ifndef LEPTONICA_ENDIANNESS_H
#define LEPTONICA_ENDIANNESS_H
/* aarch64 and x86-64 are little-endian. Generated by configure upstream. */
#define L_LITTLE_ENDIAN 1
/* #undef L_BIG_ENDIAN */
#endif
HDR

echo "leptonica: wrote src/endianness.h (L_LITTLE_ENDIAN)"
